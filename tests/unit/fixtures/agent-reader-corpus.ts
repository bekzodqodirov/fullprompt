/**
 * The free-text readers' regression corpus (fix pass 4 of the full AI seller's part 1 — the lead's call after three
 * fix passes that each reopened what the one before had closed; DECISIONS #1463-#1468 met the same trap on the intake
 * readers and the cure was a corpus). Every case a review, a check or a fix pass named for one of this round's readers
 * is here, with the answer the finding said is right, and `tests/unit/agent-reader-corpus.test.ts` runs every one
 * against the real function on every run. ANY change to one of these readers runs the WHOLE corpus first:
 *
 *  - `avia`         — the armed avia rule (run `withAviaRule` / `talksDelivery`): does a reply in a flight's chat ask
 *                     HIM («held») or go with the price act armed («goes»)? With the act OFF every quoted flight asks
 *                     him, whatever the reply — the runner checks that too, for every case.
 *  - `destination`  — `memoryFor`'s `foreignDestination` (destination `namesForeignPlace`) under an admitted quote.
 *  - `language`     — `memoryFor`'s `customerLocale` (locale `detectLocale`) under the gate's language clause.
 *  - `owner_figure` — his ✍️ answer (owner-answer `answerHoldsFigure`, digits `holdsNumeral`) under `owner_figure`.
 *  - `money`        — a reply through the policy and the gate: `money_unread` (digits `currencyBesideQuantity`) and the
 *                     word-numeral G1 beside it.
 *  - `han`          — a Chinese reply through the policy and the gate: `numeral_unread` and G1's `han_numeral`.
 *  - `han_g1`       — G1's `han_numeral` alone: his ✅ (a Chinese reply he cannot approve is his to ✏️).
 *  - `lesson`       — «📝 Tuzatish»'s money refusal (lessons `lessonShapeRefusal`).
 *  - `phone`        — the ✍️ door's phone refusal (owner-answer `answerTextRefusal`, numbers `phonesIn`).
 *
 * `kind`: `dangerous` — the WRONG answer lets something reach a customer that must not (a price nobody read, a
 * hand-over in an air chat, a Tashkent price for another destination, a reply in the wrong language, his figure
 * relayed without his ✅, a price saved as a lesson, a phone accepted); ZERO of these may fail, ever. `ordinary` — the
 * wrong answer only holds an ordinary reply (or answer) for his ✅, or makes it his question; one that cannot go
 * without opening a dangerous case, or without guessing grammar no rule reads reliably, is on the ratchet
 * (`agent-reader-corpus-known.ts`) with its reason.
 *
 * `expect` is what the reader must answer: `held` (it asks him / refuses / waits) or `goes`. Every dangerous case
 * expects `held` and every ordinary one `goes` — the corpus states it per case so a reader of the file need not know
 * the rule. `source`: where the case came from — `check2#N` (the check of fix pass 3, item N), `check1:` (the check
 * of passes 1-2), `review:<lens>#N` (the review of 0148 as built), `pinned:` (a fix pass's own test, which stays).
 *
 * Literal inputs only: nothing here is computed by the code under test.
 */

export type Reader = 'avia' | 'destination' | 'language' | 'owner_figure' | 'money' | 'han' | 'han_g1' | 'lesson' | 'phone';
export type Kind = 'dangerous' | 'ordinary';
export type Observed = 'held' | 'goes';

export interface ReaderCase {
  id: string;
  reader: Reader;
  /** The reply, the customer's lines («\n» between them), his answer, the lesson — what the reader reads. */
  input: string;
  /** `language`: the conversation's stored language and the reply's; `money` / `han`: the reply's language. */
  context?: { stored?: string | null; reply?: string };
  expect: Observed;
  kind: Kind;
  source: string;
}

type Row = readonly [id: string, input: string, source: string, context?: ReaderCase['context']];
const rows = (reader: Reader, kind: Kind, list: readonly Row[]): ReaderCase[] =>
  list.map(([id, input, source, context]) => ({
    id,
    reader,
    input,
    ...(context ? { context } : {}),
    expect: kind === 'dangerous' ? 'held' : 'goes',
    kind,
    source,
  }));

